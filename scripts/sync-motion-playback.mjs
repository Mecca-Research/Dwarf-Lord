// Keep the standalone art reviewer and game on the exact same controller.
import { readFileSync, writeFileSync } from 'node:fs';
import ts from 'typescript';
export function compiledPlayback() {
  const source = readFileSync(new URL('../src/game/motion-playback.ts', import.meta.url), 'utf8');
  return '// Generated by scripts/sync-motion-playback.mjs; edit src/game/motion-playback.ts.\n' +
    ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText;
}
if (process.argv[1] && new URL(import.meta.url).pathname === process.argv[1]) {
  writeFileSync(new URL('../public/motion-playback.mjs', import.meta.url), compiledPlayback());
}
